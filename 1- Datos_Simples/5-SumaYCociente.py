#Escribir un programa que lea dos valores enteros e informe la suma y su cociente

n1 = int(input("Por favor, escribe su primer numero: "))
n2 = int(input("Por favor, escribe su segundo numero: "))

suma = n1 + n2
cociente = n1 / n2

print(f"La suma dio como resultado: {suma}")
print(f"El cociente dio como resultado: {cociente}")